// ── Chat route edge cases not covered by tests/api/routes.chat.test.ts ──────
//
// The main chat test file covers the happy path, validation and the
// chatRun-throws-an-Error path. These tests fill the remaining gaps: the
// workingDirectory-missing fallback-to-worktree-root logic (lines ~114-127
// of src/api/routes.ts) and the non-Error rejection branch in the catch
// block (line ~145).
describe("POST /api/runs/:id/chat (working directory fallback)", () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  it("falls back to the main repo dir when the worktree dir is gone, and still succeeds", async () => {
    const mainRepoDir = mkdtempSync(join(tmpdir(), "routes-runs-chat-main-"));
    const worktreePath = join(mainRepoDir, ".worktrees", "run-1");
    const run = makeRun({ workingDirectory: worktreePath });

    const { app, mockRunRepo, mockClaudeCodeRunner } = await buildApp();
    mockRunRepo.findById.mockResolvedValue(run);

    const res = await app.inject({
      method: "POST",
      url: "/api/runs/run-1/chat",
      payload: { message: "Hello" },
    });

    expect(res.statusCode).toBe(200);
    const [input] = mockClaudeCodeRunner!.chatRun.mock.calls[0] as [{ workingDirectory: string }];
    expect(input.workingDirectory).toBe(mainRepoDir);
  });

  it("returns 422 when neither the worktree dir nor the main repo dir exist", async () => {
    const run = makeRun({
      workingDirectory: "/nonexistent-root/.worktrees/run-1",
    });

    const { app, mockRunRepo } = await buildApp();
    mockRunRepo.findById.mockResolvedValue(run);

    const res = await app.inject({
      method: "POST",
      url: "/api/runs/run-1/chat",
      payload: { message: "Hello" },
    });

    expect(res.statusCode).toBe(422);
    expect(res.json()).toEqual({
      error: "Working directory not found — the repository may have been removed",
    });
  });

  it("returns 422 when workingDirectory is missing entirely and has no /.worktrees/ segment", async () => {
    const run = makeRun({ workingDirectory: "/totally/nonexistent/dir" });

    const { app, mockRunRepo } = await buildApp();
    mockRunRepo.findById.mockResolvedValue(run);

    const res = await app.inject({
      method: "POST",
      url: "/api/runs/run-1/chat",
      payload: { message: "Hello" },
    });

    expect(res.statusCode).toBe(422);
  });

  it("returns 500 when chatRun rejects with a non-Error value", async () => {
    const workspaceDir = mkdtempSync(join(tmpdir(), "routes-runs-chat-nonerror-"));
    const run = makeRun({ workingDirectory: workspaceDir });

    const { app, mockRunRepo } = await buildApp({
      chatRunner: { chatRun: vi.fn().mockRejectedValue("subprocess exploded") },
    });
    mockRunRepo.findById.mockResolvedValue(run);

    const res = await app.inject({
      method: "POST",
      url: "/api/runs/run-1/chat",
      payload: { message: "Hello" },
    });

    expect(res.statusCode).toBe(500);
    expect(res.json()).toEqual({ error: "Chat request failed" });
  });
});
